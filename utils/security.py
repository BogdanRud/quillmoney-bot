"""
Утилиты безопасности: экранирование пользовательского текста перед вставкой
в HTML-сообщения Telegram (parse_mode="HTML").

Имя пользователя, username, текст заявок и т.п. полностью контролируются
самим пользователем. Если вставить их в HTML-сообщение без экранирования,
можно либо сломать парсинг (Telegram вернёт ошибку при отправке), либо —
что хуже — внедрить рабочую ссылку <a href="..."> в уведомление администратору,
которая выглядит как часть легитимного сообщения бота (фишинг).
"""
import html


def tg_escape(text) -> str:
    """Экранировать текст для безопасной вставки в Telegram HTML-сообщение."""
    if text is None:
        return ""
    return html.escape(str(text), quote=False)
