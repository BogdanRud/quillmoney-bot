def t(key: str, lang: str = DEFAULT_LANG, **kwargs) -> str:
    """Вернуть перевод по ключу. При отсутствии перевода/ключа — фолбэк на
    английский, затем на русский, затем сам ключ (чтобы не падать молча)."""
    lang = lang if lang in TRANSLATIONS else DEFAULT_LANG
    text = (
        TRANSLATIONS.get(lang, {}).get(key)
        or TRANSLATIONS[DEFAULT_LANG].get(key)
        or TRANSLATIONS["ru"].get(key)
        or key
    )
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def lang_name(lang: str) -> str:
    return LANG_NAMES.get(lang, lang)


def all_variants(key: str) -> frozenset:
    """Все переводы данного ключа по всем поддерживаемым языкам — для
    фильтров маршрутизации (F.text.in_(...)), которые должны узнавать кнопку
    независимо от того, на каком языке она была показана конкретному
    пользователю (фильтр строится один раз при регистрации роутера, до того
    как известно, кто и на каком языке пишет)."""
    return frozenset(t(key, lang) for lang in SUPPORTED_LANGS)


